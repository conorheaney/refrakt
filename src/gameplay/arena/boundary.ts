import type { FieldDef } from '../config';
import { FOREST_OUTLINE } from '../../content/outlines/forest';
import type { SweepHit } from './collision';
import type { Ball } from '../types';

/**
 * The arena boundary the ball bounces off, behind one small interface so worlds can use different shapes:
 *
 * - `'rect'`: the original arena - straight side walls at +/-halfWidth, a flat ceiling at `top` and two
 *   rounded top corners of `cornerRadius` (FieldDef). Space uses it.
 * - `'outline'`: a traced polyline (e.g. the inside edge of the forest painting's tree arch; data in
 *   content/outlines/forest.ts, generated by tools/trace_arch_outline.py). The ball reflects off the local
 *   surface direction wherever it touches.
 *
 * A world picks one with `boundary` (and `outline`, the data set) on its WorldDef; absent means 'rect'.
 * Only the ball uses this. Lasers, power-ups, enemy shots and debris keep the rectangular bounds.
 */
export type BoundaryKind = 'rect' | 'outline';

/** Outline data sets by name (WorldDef.outline). Each is x0, y0, x1, y1, ... in world units, opening on the right-hand side. */
export const OUTLINES: Readonly<Record<string, readonly number[]>> = {
  forest: FOREST_OUTLINE,
};

export interface ArenaBoundary {
  readonly kind: BoundaryKind;
  /**
   * Earliest contact of a ball of radius r whose centre moves from (x, y) by (dx, dy): fills `out` (t = fraction
   * of the motion in [0, 1], n = unit normal pointing back into the arena) and returns true, or returns false.
   */
  sweep(x: number, y: number, dx: number, dy: number, r: number, out: SweepHit): boolean;
  /** Pushes a ball that overlaps the boundary back inside; `reflect` turns it away from a surface normal. */
  depenetrate(ball: Ball, r: number, reflect: (nx: number, ny: number) => void): void;
  /** The boundary as a polyline (x0, y0, ...), down to `bottom`, for the `?debugArena` overlay. */
  path(bottom: number): number[];
}

const CONTACT_EPS = 1e-4;

/**
 * Parametric time (in units of the motion vector) at which a point moving by (dx, dy) from (px, py) leaves a
 * circle of radius `radius` centred at (cx, cy), i.e. the larger ray/circle root; -1 when the ray misses it.
 */
function cornerExit(px: number, py: number, dx: number, dy: number, cx: number, cy: number, radius: number): number {
  const fx = px - cx;
  const fy = py - cy;
  const a = dx * dx + dy * dy;
  if (a < 1e-12) return -1;
  const b = 2 * (fx * dx + fy * dy);
  const c = fx * fx + fy * fy - radius * radius;
  const disc = b * b - 4 * a * c;
  if (disc < 0) return -1;
  return (-b + Math.sqrt(disc)) / (2 * a);
}

/** The original rectangular arena with rounded top corners (unchanged behaviour, moved here from World). */
export class RectBoundary implements ArenaBoundary {
  readonly kind = 'rect' as const;
  private readonly cornerX: number;
  private readonly cornerY: number;

  constructor(private readonly field: FieldDef) {
    this.cornerX = field.halfWidth - field.cornerRadius;
    this.cornerY = field.top - field.cornerRadius;
  }

  // Straight sides and a flat top, each only valid outside the rounded corner zones, plus two concave
  // quarter-circle corners (the field is convex, so the earliest valid candidate is the true exit point).
  sweep(x: number, y: number, dx: number, dy: number, r: number, out: SweepHit): boolean {
    const field = this.field;
    const cornerX = this.cornerX;
    const cornerY = this.cornerY;
    let bestT = 1;
    let found = false;
    if (dx < 0) {
      const t = (-field.halfWidth + r - x) / dx;
      if (t < bestT && y + dy * Math.max(0, t) <= cornerY) {
        bestT = Math.max(0, t);
        out.nx = 1;
        out.ny = 0;
        found = true;
      }
    } else if (dx > 0) {
      const t = (field.halfWidth - r - x) / dx;
      if (t < bestT && y + dy * Math.max(0, t) <= cornerY) {
        bestT = Math.max(0, t);
        out.nx = -1;
        out.ny = 0;
        found = true;
      }
    }
    if (dy > 0) {
      const t = (field.top - r - y) / dy;
      if (t < bestT && Math.abs(x + dx * Math.max(0, t)) <= cornerX) {
        bestT = Math.max(0, t);
        out.nx = 0;
        out.ny = -1;
        found = true;
      }
    }
    if (dy > 0 || y > cornerY) {
      for (let side = -1; side <= 1; side += 2) {
        const t = cornerExit(x, y, dx, dy, side * cornerX, cornerY, field.cornerRadius - r);
        if (t < 0 || t >= bestT) continue;
        const hx = x + dx * t;
        const hy = y + dy * t;
        if (side * hx < cornerX || hy < cornerY) continue;
        const len = Math.hypot(hx - side * cornerX, hy - cornerY) || 1;
        bestT = t;
        out.nx = (side * cornerX - hx) / len;
        out.ny = (cornerY - hy) / len;
        found = true;
      }
    }
    out.t = bestT;
    return found;
  }

  depenetrate(ball: Ball, r: number, reflect: (nx: number, ny: number) => void): void {
    const field = this.field;
    const cornerX = this.cornerX;
    const cornerY = this.cornerY;
    const limit = field.halfWidth - r;
    if (ball.x < -limit) {
      ball.x = -limit;
      if (ball.dx < 0) ball.dx = -ball.dx;
    } else if (ball.x > limit) {
      ball.x = limit;
      if (ball.dx > 0) ball.dx = -ball.dx;
    }
    if (ball.y > field.top - r) {
      ball.y = field.top - r;
      if (ball.dy > 0) ball.dy = -ball.dy;
    }
    // Rounded top corners of the arch frame.
    const side = ball.x < 0 ? -1 : 1;
    if (side * ball.x > cornerX && ball.y > cornerY) {
      const ox = ball.x - side * cornerX;
      const oy = ball.y - cornerY;
      const d = Math.hypot(ox, oy);
      const max = field.cornerRadius - r;
      if (d > max) {
        ball.x = side * cornerX + (ox / d) * (max - CONTACT_EPS);
        ball.y = cornerY + (oy / d) * (max - CONTACT_EPS);
        reflect(-ox / d, -oy / d);
      }
    }
  }

  path(bottom: number): number[] {
    const f = this.field;
    const pts = [-f.halfWidth, bottom];
    for (let i = 0; i <= 24; i++) {
      const a = Math.PI - (i / 24) * (Math.PI / 2);
      pts.push(-this.cornerX + Math.cos(a) * f.cornerRadius, this.cornerY + Math.sin(a) * f.cornerRadius);
    }
    for (let i = 0; i <= 24; i++) {
      const a = Math.PI / 2 - (i / 24) * (Math.PI / 2);
      pts.push(this.cornerX + Math.cos(a) * f.cornerRadius, this.cornerY + Math.sin(a) * f.cornerRadius);
    }
    pts.push(f.halfWidth, bottom);
    return pts;
  }
}

/**
 * A traced outline: the ball (a circle) against a polyline whose opening is on the right-hand side of the
 * direction of travel. Swept exactly against each segment (offset inward by the radius) and each vertex (a
 * circle of the radius), so a ball cannot tunnel through at any speed. Concave vertices are never reached
 * first (the neighbouring segments stop the ball before), so only convex bumps need the vertex test, but all
 * are tested for simplicity.
 */
export class OutlineBoundary implements ArenaBoundary {
  readonly kind = 'outline' as const;
  /** Vertices. */
  private readonly px: Float64Array;
  private readonly py: Float64Array;
  /** Per segment i (vertex i -> i + 1): unit inward normal, length, and bounding box. */
  private readonly nx: Float64Array;
  private readonly ny: Float64Array;
  private readonly len: Float64Array;
  private readonly minX: Float64Array;
  private readonly maxX: Float64Array;
  private readonly minY: Float64Array;
  private readonly maxY: Float64Array;
  private readonly count: number;

  constructor(points: readonly number[]) {
    const n = points.length / 2;
    if (n < 3 || points.length % 2) throw new Error('An arena outline needs at least three points.');
    this.count = n;
    this.px = new Float64Array(n);
    this.py = new Float64Array(n);
    for (let i = 0; i < n; i++) {
      this.px[i] = points[i * 2];
      this.py[i] = points[i * 2 + 1];
    }
    const s = n - 1;
    this.nx = new Float64Array(s);
    this.ny = new Float64Array(s);
    this.len = new Float64Array(s);
    this.minX = new Float64Array(s);
    this.maxX = new Float64Array(s);
    this.minY = new Float64Array(s);
    this.maxY = new Float64Array(s);
    for (let i = 0; i < s; i++) {
      const ex = this.px[i + 1] - this.px[i];
      const ey = this.py[i + 1] - this.py[i];
      const l = Math.hypot(ex, ey) || 1e-9;
      this.len[i] = l;
      // Right-hand normal of the direction of travel points into the opening.
      this.nx[i] = ey / l;
      this.ny[i] = -ex / l;
      this.minX[i] = Math.min(this.px[i], this.px[i + 1]);
      this.maxX[i] = Math.max(this.px[i], this.px[i + 1]);
      this.minY[i] = Math.min(this.py[i], this.py[i + 1]);
      this.maxY[i] = Math.max(this.py[i], this.py[i + 1]);
    }
  }

  sweep(x: number, y: number, dx: number, dy: number, r: number, out: SweepHit): boolean {
    let bestT = 1;
    let found = false;
    const reach = r + Math.abs(dx) + Math.abs(dy) + 1e-6;
    const segs = this.count - 1;
    for (let i = 0; i < segs; i++) {
      if (x + reach < this.minX[i] || x - reach > this.maxX[i] || y + reach < this.minY[i] || y - reach > this.maxY[i]) continue;
      const nx = this.nx[i];
      const ny = this.ny[i];
      const ax = this.px[i];
      const ay = this.py[i];
      // Segment face: the line offset inward by r.
      const v = dx * nx + dy * ny;
      if (v < -1e-12) {
        const d0 = (x - ax) * nx + (y - ay) * ny;
        // Only from the opening's side (a centre already behind the face is left to depenetrate).
        if (d0 >= r - 1e-3) {
          const t = Math.max(0, (d0 - r) / -v);
          if (t < bestT) {
            const qx = x + dx * t - ax;
            const qy = y + dy * t - ay;
            const u = (qx * -ny + qy * nx) / this.len[i];
            if (u >= 0 && u <= 1) {
              bestT = t;
              out.nx = nx;
              out.ny = ny;
              found = true;
            }
          }
        }
      }
      // End vertex (each interior vertex is tested once; the first vertex too).
      for (let k = i === 0 ? 0 : 1; k <= 1; k++) {
        const vx = this.px[i + k];
        const vy = this.py[i + k];
        const fx = x - vx;
        const fy = y - vy;
        const b = fx * dx + fy * dy;
        if (b >= 0) continue; // moving away from the vertex
        const a = dx * dx + dy * dy;
        const c = fx * fx + fy * fy - r * r;
        let t: number;
        if (c <= 0) {
          t = 0; // already touching and moving in
        } else {
          const disc = b * b - a * c;
          if (disc < 0) continue;
          t = (-b - Math.sqrt(disc)) / a;
        }
        if (t < 0 || t >= bestT) continue;
        const hx = x + dx * t - vx;
        const hy = y + dy * t - vy;
        const l = Math.hypot(hx, hy) || 1;
        bestT = t;
        out.nx = hx / l;
        out.ny = hy / l;
        found = true;
      }
    }
    out.t = bestT;
    return found;
  }

  /**
   * Nearest point of the outline to (x, y): returns the distance and fills `out` with the unit direction from
   * that point towards the opening (for a point on the wrong side, the direction back into the opening).
   */
  nearest(x: number, y: number, out: SweepHit): number {
    let best = Infinity;
    let bx = 0;
    let by = 0;
    let bi = 0;
    let bu = 0;
    const segs = this.count - 1;
    for (let i = 0; i < segs; i++) {
      const ax = this.px[i];
      const ay = this.py[i];
      const ex = this.px[i + 1] - ax;
      const ey = this.py[i + 1] - ay;
      const l2 = ex * ex + ey * ey || 1e-18;
      const u = Math.max(0, Math.min(1, ((x - ax) * ex + (y - ay) * ey) / l2));
      const cx = ax + ex * u;
      const cy = ay + ey * u;
      const d = Math.hypot(x - cx, y - cy);
      if (d < best) {
        best = d;
        bx = cx;
        by = cy;
        bi = i;
        bu = u;
      }
    }
    // Which side: the segment's inward normal, or at a vertex the average of the two segments' normals.
    let nx = this.nx[bi];
    let ny = this.ny[bi];
    if (bu <= 0 && bi > 0) {
      nx += this.nx[bi - 1];
      ny += this.ny[bi - 1];
    } else if (bu >= 1 && bi < segs - 1) {
      nx += this.nx[bi + 1];
      ny += this.ny[bi + 1];
    }
    const inside = (x - bx) * nx + (y - by) * ny >= 0;
    if (best > 1e-9) {
      const s = inside ? 1 : -1;
      out.nx = (s * (x - bx)) / best;
      out.ny = (s * (y - by)) / best;
    } else {
      const l = Math.hypot(nx, ny) || 1;
      out.nx = nx / l;
      out.ny = ny / l;
    }
    out.t = inside ? best : -best;
    return out.t;
  }

  private readonly tmp: SweepHit = { t: 0, nx: 0, ny: 0 };

  depenetrate(ball: Ball, r: number, reflect: (nx: number, ny: number) => void): void {
    // A couple of passes settle a ball wedged into a concave spot between two segments.
    for (let pass = 0; pass < 3; pass++) {
      const d = this.nearest(ball.x, ball.y, this.tmp);
      if (d >= r) return;
      const push = r - d + CONTACT_EPS;
      ball.x += this.tmp.nx * push;
      ball.y += this.tmp.ny * push;
      reflect(this.tmp.nx, this.tmp.ny);
    }
  }

  path(): number[] {
    const pts: number[] = [];
    for (let i = 0; i < this.count; i++) pts.push(this.px[i], this.py[i]);
    return pts;
  }
}

/**
 * The boundary a world asks for; `override` (e.g. from `?boundary=`) wins when it can be honoured (asking for
 * 'outline' in a world without outline data keeps the rectangle).
 */
export function createBoundary(
  world: { readonly field: FieldDef; readonly boundary?: BoundaryKind; readonly outline?: string },
  override: BoundaryKind | null = null,
): ArenaBoundary {
  const kind = override ?? world.boundary ?? 'rect';
  const points = world.outline ? OUTLINES[world.outline] : undefined;
  if (kind === 'outline' && points) return new OutlineBoundary(points);
  return new RectBoundary(world.field);
}

/** Parses a `?boundary=` value: 'rect' or 'outline', anything else (or absent) means no override. */
export function parseBoundaryOverride(value: string | null): BoundaryKind | null {
  return value === 'rect' || value === 'outline' ? value : null;
}

/**
 * Frees a ball that is trapped by the boundary: one that touches it many times in a short window without
 * getting anywhere (a concave pocket, or bouncing in place). The ball is turned towards the middle of the
 * arena; the caller renormalises the direction (keeping the minimum vertical speed rule).
 */
export class TrapGuard {
  /** Boundary contacts within WINDOW seconds that count as trapped, unless the ball travelled TRAVEL units. */
  static readonly HITS = 6;
  static readonly WINDOW = 0.4;
  static readonly TRAVEL = 2.5;
  private readonly state = new Map<Ball, { since: number; hits: number; x: number; y: number }>();
  /** Times a ball has been freed (for tests and diagnostics). */
  freed = 0;

  reset(): void {
    this.state.clear();
  }

  /** Call on each boundary contact; returns true (and redirects the ball) when it is trapped. */
  onContact(ball: Ball, time: number, centreX: number, centreY: number): boolean {
    let s = this.state.get(ball);
    if (!s || time - s.since > TrapGuard.WINDOW) {
      s = { since: time, hits: 0, x: ball.x, y: ball.y };
      this.state.set(ball, s);
    }
    s.hits++;
    if (s.hits < TrapGuard.HITS || Math.hypot(ball.x - s.x, ball.y - s.y) > TrapGuard.TRAVEL) return false;
    this.free(ball, centreX, centreY);
    return true;
  }

  /** Turns a ball towards (centreX, centreY) and forgets its contact history. */
  free(ball: Ball, centreX: number, centreY: number): void {
    const tx = centreX - ball.x;
    const ty = centreY - ball.y;
    const l = Math.hypot(tx, ty) || 1;
    ball.dx = tx / l;
    ball.dy = ty / l;
    this.state.delete(ball);
    this.freed++;
  }
}
